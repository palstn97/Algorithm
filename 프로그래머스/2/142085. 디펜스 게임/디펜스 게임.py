# 무적권을 어느 라운드에 쓸지는 게임을 진행하면서 병사가 부족해지는 순간에만 정확히 판단이 가능하다! 실제로 병사가 부족해지는 순간이 왔을 때, 지금까지 병사로 쓴 것 중 가장 아까웠던 걸 무적권으로 바꿔치는 방식으로 진행을 하자.
# 지금가지 병사로 처리한 라운드들 중, 가장 많이 소모한 것을 빠르게 찾아야하기 때문에 힙을 사용.
import heapq

def solution(n, k, enemy):
    heap = []
    for i, e in enumerate(enemy):
        heapq.heappush(heap, e) # 이번 라운드의 적의 수를 힙에 넣어서 일단 이번 라운드는 무적권을 썼다고 생각하고 힙에 저장을 하는 것이다. 이때는 아직 병사를 소모하지 않았다.
        if len(heap) > k:
            # 무적권의 개수(k)를 넘어가면 가장 작은 소모값을 힙에서 빼서 병사로 처리한다.
            n -= heapq.heappop(heap)    # heappop은 힙에서 가장 작은 값을 꺼내면서 동시에 그 값을 힙에서 제거한다. 즉 가장 작은 값을 골라서 실제 병사로 처리한다. 가장 작은 것을 고르는 이유는 무적권은 k번만 쓸 수 있으니까 가장 작은 숫자는 병사로 처리를 해버리면 아낄 수 있다.
            
        if n < 0:
            return i
    
    return len(enemy)